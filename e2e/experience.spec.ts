import { test, expect } from '@playwright/test'

test('discover, consent, check-in, redemption, ledger, reward demo and admin',async({page},info)=>{
  const errors:string[]=[];page.on('pageerror',e=>errors.push(e.message))
  await page.goto('/')
  await expect(page.getByText('让日常，多一点惊喜')).toBeVisible()
  await expect(page.locator('.product-card')).toHaveCount(4)
  await expect(page.locator('.load-error')).toHaveCount(0)
  const imgs=page.locator('.product-image img,.hero-art img')
  await expect.poll(async()=>imgs.evaluateAll(nodes=>nodes.every(n=>(n as HTMLImageElement).complete&&(n as HTMLImageElement).naturalWidth>0))).toBeTruthy()
  await page.screenshot({path:`docs/screenshots/${info.project.name}-home.png`,fullPage:true})
  const nav=(tab:string)=>page.locator(info.project.name==='mobile'?'.mobile-nav':'.nav-list').getByText(tab,{exact:true})
  await nav(info.project.name==='mobile'?'任务':'赚取积分').click()
  await page.getByRole('button',{name:'签到领取积分'}).click()
  await expect(page.getByText('好生活，从这里开始')).toBeVisible()
  await page.locator('.consent-row').click()
  await page.getByRole('button',{name:'同意并开启体验'}).click()
  await expect(page.locator('.modal-mask')).toHaveCount(0)
  await page.getByRole('button',{name:'签到领取积分'}).click()
  await expect(page.getByRole('button',{name:'今日已签到 · 明天见'})).toBeDisabled()
  await page.getByRole('button',{name:'去体验'}).click()
  await expect(page.getByText('内部演示 · 非真实广告')).toBeVisible()
  await expect(page.getByRole('button',{name:'领取 30 演示积分'})).toBeEnabled({timeout:15000})
  await page.getByRole('button',{name:'领取 30 演示积分'}).click()
  await expect(page.locator('.modal-mask')).toHaveCount(0)
  await nav(info.project.name==='mobile'?'好物':'精选好物').click()
  await page.locator('.product-info').filter({hasText:'山野'}).click()
  await page.getByRole('button',{name:'确认演示兑换'}).click()
  await expect(page.locator('.modal-mask')).toHaveCount(0)
  await nav(info.project.name==='mobile'?'积分':'我的积分').click()
  await expect(page.locator('.wallet-value')).toContainText('750')
  await expect(page.locator('.ledger-row')).toHaveCount(4)
  await nav(info.project.name==='mobile'?'我的':'个人中心').click()
  await expect(page.locator('.order-row')).toHaveCount(1)
  await page.locator('.settings-links').getByText('运营控制台').click()
  await page.locator('.admin-input input').fill('e2e-only-admin-credential-not-for-production')
  await page.getByRole('button',{name:'安全进入'}).click()
  await expect(page.getByText('激励广告管理',{exact:true})).toBeVisible()
  await expect(page.getByText('未接入，当前为本地规则')).toBeVisible()
  await expect(page.getByText('广告位置管理',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'开启预览'}).first().click()
  await expect(page.getByRole('button',{name:'关闭预览'})).toHaveCount(1)
  const catalog=await (await page.request.get('/api/catalog')).json()
  expect(catalog.placements[0].id).toBe('home_feature')
  await page.getByRole('button',{name:'关闭预览'}).click()
  await expect(page.getByRole('button',{name:'关闭预览'})).toHaveCount(0)
  await page.screenshot({path:`docs/screenshots/${info.project.name}-admin.png`,fullPage:true})
  expect(errors).toEqual([])
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBeTruthy()
})

test('search, empty results, favorites and privacy dialog',async({page})=>{
  await page.goto('/')
  await expect(page.locator('.product-card')).toHaveCount(4)
  await page.locator('.favorite').first().click()
  await expect(page.locator('.favorite').first()).toHaveClass(/hearted/)
  const input=page.locator('.search-box input')
  await input.fill('不存在的商品');await input.press('Enter')
  await expect(page.getByText('还没有找到这份心动')).toBeVisible()
  await page.getByRole('button',{name:'查看全部好物'}).click()
  await expect(page.locator('.product-card')).toHaveCount(6)
  await page.locator('.footer').getByText('隐私说明',{exact:true}).click()
  await expect(page.locator('.modal-card').getByText('隐私与数据说明',{exact:true})).toBeVisible()
})
